-- 앱 소유 oracle 새 스키마 DDL. 기존 H2 migration은 별도 경로에서 checksum을 보존한다.
CREATE TABLE operation_schedule (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY(START WITH 100) PRIMARY KEY,
 job_code VARCHAR2(64 CHAR) NOT NULL UNIQUE,
 cron VARCHAR2(120 CHAR) NOT NULL,
 time_zone VARCHAR2(64 CHAR) NOT NULL,
 misfire_policy VARCHAR2(10 CHAR) NOT NULL CHECK(misfire_policy IN('SKIP','FIRE_ONCE')),
 enabled NUMBER(1) NOT NULL,
 revision NUMBER(10) DEFAULT 1 NOT NULL CHECK(revision>=1),
 created_by VARCHAR2(64 CHAR) NOT NULL,
 created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE TABLE operation_job_run (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 schedule_id NUMBER(19) NOT NULL REFERENCES operation_schedule(id),
 run_key VARCHAR2(36 CHAR) NOT NULL UNIQUE,
 job_code VARCHAR2(64 CHAR) NOT NULL,
 scheduled_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 started_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 completed_at TIMESTAMP(6) WITH TIME ZONE,
 state VARCHAR2(8 CHAR) NOT NULL CHECK(state IN('RUNNING','SUCCESS','FAILED')),
 reason_code VARCHAR2(32 CHAR),
 attempt NUMBER(10) NOT NULL CHECK(attempt>=1),
 run_owner VARCHAR2(36 CHAR) NOT NULL,
 execution_token VARCHAR2(36 CHAR) NOT NULL
);
CREATE INDEX operation_run_recent ON operation_job_run(started_at DESC,id DESC);
CREATE INDEX operation_run_schedule ON operation_job_run(schedule_id,started_at DESC,id DESC);
CREATE INDEX operation_run_retention ON operation_job_run(completed_at,id);
CREATE TABLE operation_pulse_effect (
 run_key VARCHAR2(36 CHAR) PRIMARY KEY,
 occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE TABLE browser_error_group (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fingerprint VARCHAR2(64 CHAR) NOT NULL UNIQUE,
 app_version VARCHAR2(64 CHAR) NOT NULL,
 source VARCHAR2(9 CHAR) NOT NULL CHECK(source IN('VUE','WINDOW','REJECTION')),
 event_code VARCHAR2(32 CHAR) NOT NULL CHECK(event_code IN('VUE_ERROR','WINDOW_ERROR','UNHANDLED_REJECTION','UNKNOWN_RUNTIME')),
 route_code VARCHAR2(64 CHAR) NOT NULL,
 component_code VARCHAR2(64 CHAR) NOT NULL CHECK(component_code='ROOT'),
 first_seen_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 last_seen_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 occurrence_count NUMBER(19) NOT NULL CHECK(occurrence_count>=0)
);
CREATE INDEX browser_error_group_recent ON browser_error_group(last_seen_at DESC,id DESC);
CREATE TABLE browser_error_occurrence (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 group_id NUMBER(19) NOT NULL REFERENCES browser_error_group(id),
 actor_id NUMBER(19),
 actor_subject VARCHAR2(64 CHAR) NOT NULL,
 request_id VARCHAR2(64 CHAR),
 occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX browser_error_occurrence_group ON browser_error_occurrence(group_id,occurred_at DESC,id DESC);
CREATE INDEX browser_error_occurrence_retention ON browser_error_occurrence(occurred_at,id);
CREATE TABLE browser_error_receipt (
 client_event_id VARCHAR2(36 CHAR) NOT NULL,
 actor_subject VARCHAR2(64 CHAR) NOT NULL,
 fingerprint VARCHAR2(64 CHAR) NOT NULL,
 received_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 PRIMARY KEY(client_event_id,actor_subject)
);
CREATE INDEX browser_error_receipt_retention ON browser_error_receipt(received_at,client_event_id);
