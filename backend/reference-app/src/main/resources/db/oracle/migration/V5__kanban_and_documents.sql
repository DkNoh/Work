CREATE TABLE kanban_member (
    user_id NUMBER(19) PRIMARY KEY REFERENCES reference_user(id)
);
CREATE TABLE kanban_board (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
    title VARCHAR2(100 CHAR) NOT NULL CHECK (LENGTH(title) BETWEEN 1 AND 100),
    author_id NUMBER(19) REFERENCES reference_user(id),
    revision NUMBER(10) DEFAULT 1 NOT NULL CHECK (revision >= 1),
    command_sequence NUMBER(19) DEFAULT 0 NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CHECK (id = 1 OR author_id IS NOT NULL)
);
